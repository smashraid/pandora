package service_test

import (
	"context"
	"errors"
	"testing"
	"time"

	"github.com/smashraid/pandora/internal/adapters/outbound/memory"
	"github.com/smashraid/pandora/internal/domain"
	"github.com/smashraid/pandora/internal/service"
)

func setupService() (*service.LoanService, *memory.MemoryTaskRepository, *memory.MemoryEventBroker) {
	repo := memory.NewMemoryTaskRepository()
	broker := memory.NewMemoryEventBroker()
	svc := service.NewLoanService(repo, broker, broker)
	return svc, repo, broker
}

func TestLoanService_SubmitApplication(t *testing.T) {
	svc, repo, _ := setupService()
	ctx := context.Background()

	app := &domain.LoanApplication{
		ID:                   "app-test-001",
		ApplicantEmail:       "test@example.com",
		RequestedAmountCents: 1000000,
		Priority:             domain.PriorityHigh,
		CreatedAt:            time.Now().UTC(),
	}

	// 1. Submit application
	task, err := svc.SubmitApplication(ctx, app)
	if err != nil {
		t.Fatalf("expected no error submitting application, got: %v", err)
	}

	if task.TaskID == "" {
		t.Error("expected non-empty TaskID generated by service")
	}
	if task.ApplicationID != app.ID {
		t.Errorf("expected ApplicationID %s, got %s", app.ID, task.ApplicationID)
	}
	if task.Status != domain.TaskStatusPending {
		t.Errorf("expected initial status %s, got %s", domain.TaskStatusPending, task.Status)
	}

	// 2. Verify application saved in repo
	savedApp, err := repo.GetApplicationByID(ctx, app.ID)
	if err != nil {
		t.Fatalf("expected application to be saved in repository, got: %v", err)
	}
	if savedApp.ApplicantEmail != app.ApplicantEmail {
		t.Errorf("expected email %s, got %s", app.ApplicantEmail, savedApp.ApplicantEmail)
	}
}

